# Rebuilds the Emscripten-compiled Wasm workloads used by the experimental
# benchmarks. The build output is checked into the repository so that
# Emscripten is NOT required for `npm run build`, CI, or deployments.
#
# Run this manually (with emsdk activated) only when you want to refresh the
# checked-in binaries, e.g. after bumping a source commit or compiler flags,
# then commit the updated files under src/<workload>/build/.
#
# Usage: ./build-wasm-workloads.sh

set -euo pipefail

EXPERIMENTAL_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"

CC="${CC:-emcc}"
CXX="${CXX:-em++}"
if ! command -v "$CC" >/dev/null 2>&1 || ! command -v "$CXX" >/dev/null 2>&1; then
  echo "Error: $CC / $CXX not found. Please activate emsdk or set CC and CXX." >&2
  exit 1
fi
EMCC_VERSION="$("$CC" --version | head -n 1)"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

###############################################################################
# GGML (test-quantize-perf) -> src/ggml/build/
###############################################################################
build_ggml() {
  local OUT_DIR="$EXPERIMENTAL_DIR/src/ggml/build"
  local GGML_SRC="$WORK_DIR/ggml"

  # v0.9.4
  local GGML_VERSION="0.9.4"
  local GGML_COMMIT="72632094336524a9c809e129e8b1c52154543a5a"

  local CFLAGS=(
    -O3
    -fno-exceptions
    -mbulk-memory
    -mextended-const
    -mmultivalue
    -mmutable-globals
    -mnontrapping-fptoint
    -mrelaxed-simd
    -msign-ext
    -msimd128
  )

  local EM_LDFLAGS=(
    -sENVIRONMENT=web
    -sMODULARIZE=1
    -sEXPORT_ES6=1
    -sALLOW_MEMORY_GROWTH=1
  )

  local DEFINES=(
    -DGGML_USE_CPU
    -DGGML_VERSION=\"$GGML_VERSION\"
    -DGGML_COMMIT=\"$GGML_COMMIT\"
  )

  local INCLUDES=(
    -I "$GGML_SRC/src"
    -I "$GGML_SRC/src/ggml/"
    -I "$GGML_SRC/src/ggml-cpu/"
    -I "$GGML_SRC/include"
  )

  echo "[ggml] Downloading GGML source ($GGML_COMMIT)..."
  mkdir -p "$GGML_SRC"
  curl -LSsf "https://github.com/ggml-org/ggml/archive/$GGML_COMMIT.tar.gz" \
    | tar --strip-components=1 -xz -C "$GGML_SRC"

  local OBJ_DIR="$WORK_DIR/ggml-obj"
  mkdir -p "$OBJ_DIR"
  pushd "$OBJ_DIR" >/dev/null

  echo "[ggml] Compiling object files with $EMCC_VERSION..."
  "$CC" "${CFLAGS[@]}" "${DEFINES[@]}" "${INCLUDES[@]}" -c \
    "$GGML_SRC/src/ggml-cpu/arch/wasm/quants.c" \
    -o wasm-quants.o

  "$CC" "${CFLAGS[@]}" "${DEFINES[@]}" "${INCLUDES[@]}" -c \
    "$GGML_SRC/src/ggml.c" \
    "$GGML_SRC/src/ggml-quants.c" \
    "$GGML_SRC/src/ggml-cpu/ggml-cpu.c" \
    "$GGML_SRC/src/ggml-cpu/quants.c"

  echo "[ggml] Linking test-quantize-perf.mjs + test-quantize-perf.wasm..."
  rm -rf "$OUT_DIR"
  mkdir -p "$OUT_DIR"
  "$CXX" "${CFLAGS[@]}" "${DEFINES[@]}" "${INCLUDES[@]}" "${EM_LDFLAGS[@]}" \
    "$GGML_SRC/tests/test-quantize-perf.cpp" \
    "$GGML_SRC/src/ggml-cpu/repack.cpp" \
    "$GGML_SRC/src/ggml-cpu/traits.cpp" \
    "$GGML_SRC/src/ggml-cpu/binary-ops.cpp" \
    "$GGML_SRC/src/ggml-cpu/unary-ops.cpp" \
    "$GGML_SRC/src/ggml-cpu/vec.cpp" \
    "$GGML_SRC/src/ggml-cpu/ops.cpp" \
    "$GGML_SRC/src/ggml-threading.cpp" \
    ggml.o \
    ggml-quants.o \
    ggml-cpu.o \
    quants.o \
    wasm-quants.o \
    -o "$OUT_DIR/test-quantize-perf.mjs"

  popd >/dev/null

  cp "$GGML_SRC/LICENSE" "$OUT_DIR/LICENSE"

  cat > "$OUT_DIR/README.md" <<EOF
# GGML test-quantize-perf (Wasm)

Auto-generated by \`resources/experimental/build-wasm-workloads.sh\`. Do not edit manually.

The files in this directory are checked in so that Emscripten is not required
to build or deploy the benchmark. To refresh them, activate emsdk and run:

\`\`\`bash
resources/experimental/build-wasm-workloads.sh
\`\`\`

- Source: [ggml](https://github.com/ggml-org/ggml) v$GGML_VERSION ([\`$GGML_COMMIT\`](https://github.com/ggml-org/ggml/tree/$GGML_COMMIT))
- Compiler: \`$EMCC_VERSION\`
- CFLAGS: \`${CFLAGS[*]}\`
- LDFLAGS: \`${EM_LDFLAGS[*]}\`
EOF

  echo "[ggml] Successfully built GGML Wasm module in $OUT_DIR"
}

build_ggml

echo "Done. Review and commit the updated build output under src/*/build/."
