set -euo pipefail
export LC_ALL=C

EIGEN_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
OUT_DIR="$EIGEN_DIR/build"

CXX="${CXX:-em++}"
if ! command -v "$CXX" >/dev/null 2>&1; then
  echo "Error: $CXX not found. Please activate emsdk or set CXX." >&2
  exit 1
fi
EMCC_VERSION="$("$CXX" --version | head -n 1)"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

EIGEN_SRC="$WORK_DIR/eigen"
BENCH="$EIGEN_SRC/bench"
STAGE_DIR="$WORK_DIR/out"

EIGEN_COMMIT="e0a59e5a66e6d16fa93ab4f5e48bf539205e837f"

DEFAULT_CFLAGS=(
  -O3
  -fno-exceptions
  -mbulk-memory
  -mextended-const
  -mmultivalue
  -mmutable-globals
  -mnontrapping-fptoint
  -mrelaxed-simd
  -msign-ext
  -msimd128
)
if [[ -n "${CFLAGS:-}" ]]; then
  read -r -a CFLAGS_ARR <<< "$CFLAGS"
else
  CFLAGS_ARR=("${DEFAULT_CFLAGS[@]}")
fi

EM_LDFLAGS=(
  -sENVIRONMENT=web
  -sMODULARIZE=1
  -sEXPORT_ES6=1
)

PREFIX_MAP_FLAGS=(
  -ffile-prefix-map="$EIGEN_SRC"=eigen
)

echo "[eigen] Downloading Eigen source ($EIGEN_COMMIT)..."
mkdir -p "$EIGEN_SRC"
curl -LSsf "https://gitlab.com/libeigen/eigen/-/archive/$EIGEN_COMMIT/eigen-$EIGEN_COMMIT.tar.gz" \
  | tar --strip-components=1 -xz -C "$EIGEN_SRC"

mkdir -p "$STAGE_DIR"

echo "[eigen] Compiling eig33.mjs + eig33.wasm with $EMCC_VERSION..."
"$CXX" "${CFLAGS_ARR[@]}" "${PREFIX_MAP_FLAGS[@]}" "${EM_LDFLAGS[@]}" \
  "$BENCH/eig33.cpp" \
  -I "$EIGEN_SRC" \
  -o "$STAGE_DIR/eig33.mjs"

echo "[eigen] Compiling geometry.mjs + geometry.wasm with $EMCC_VERSION..."
"$CXX" "${CFLAGS_ARR[@]}" "${PREFIX_MAP_FLAGS[@]}" "${EM_LDFLAGS[@]}" \
  "$BENCH/geometry.cpp" \
  -I "$EIGEN_SRC" \
  -o "$STAGE_DIR/geometry.mjs"

cat > "$STAGE_DIR/README.md" <<EOF
# Eigen eig33 & geometry (Wasm)

Auto-generated by \`resources/experimental/build-wasm-workloads.sh\`. Do not edit manually.

The files in this directory are checked in so that Emscripten is not required
to build or deploy the benchmark. To refresh them, activate emsdk and run:

\`\`\`bash
resources/experimental/build-wasm-workloads.sh eigen
\`\`\`

- Source: [Eigen](https://gitlab.com/libeigen/eigen) ([\`$EIGEN_COMMIT\`](https://gitlab.com/libeigen/eigen/-/tree/$EIGEN_COMMIT))
- Compiler: \`$EMCC_VERSION\`
- CFLAGS: \`${CFLAGS_ARR[*]}\`
- LDFLAGS: \`${EM_LDFLAGS[*]}\`
EOF

rm -rf "$OUT_DIR"
mv "$STAGE_DIR" "$OUT_DIR"

echo "[eigen] Successfully built Eigen Wasm modules in $OUT_DIR"
