set -euo pipefail
# Deterministic glob/sort order so rebuilds are reproducible across machines.
export LC_ALL=C

NCNN_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
OUT_DIR="$NCNN_DIR/build"

# Must match MODELS / PARAM_URLS in benchmark.mjs. These three models were
# chosen from ncnn's benchmark/ directory to cover distinct Wasm SIMD profiles
# (INT8 integer kernels, broad FP32 op mix, compute-bound FP32 at high res).
PARAM_FILES=(
  "efficientnetv2_b0.param"
  "resnet50_int8.param"
  "yolov4-tiny.param"
)

CXX="${CXX:-em++}"
for cmd in "$CXX" emcmake cmake curl unzip patch; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Error: $cmd not found. Please activate emsdk (em++/emcmake) and install cmake, curl, unzip and patch." >&2
    exit 1
  fi
done
EMCC_VERSION="$("$CXX" --version | head -n 1)"
CMAKE_VERSION="$(cmake --version | head -n 1)"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

NCNN_SRC="$WORK_DIR/ncnn"
BUILD_DIR="$WORK_DIR/ncnn-build"
# Build into a staging directory and only replace the checked-in output once
# everything succeeded, so a failed build never leaves src/ncnn/build/ empty.
STAGE_DIR="$WORK_DIR/out"
STAGE_DATA_DIR="$STAGE_DIR/data"

NCNN_VERSION="20241226"

echo "[ncnn] Downloading NCNN ($NCNN_VERSION)..."
mkdir -p "$NCNN_SRC"
ZIP_NAME="ncnn-$NCNN_VERSION-full-source.zip"
curl -LSfs "https://github.com/Tencent/ncnn/releases/download/$NCNN_VERSION/$ZIP_NAME" \
  -o "$WORK_DIR/$ZIP_NAME"
unzip -q "$WORK_DIR/$ZIP_NAME" -d "$NCNN_SRC"
# benchncnn mounts NODEFS under Emscripten, which is unavailable on the web.
patch -i "$NCNN_DIR/ncnn.patch" -p 1 --directory="$NCNN_SRC"

# wasm-perf builds ncnn with -O3 and -ffast-math (ncnn's CMake always enables
# fast-math) plus its common set of Wasm target features.
DEFAULT_CFLAGS=(
  -O3
  -ffast-math
  -fno-exceptions
  -mbulk-memory
  -mextended-const
  -mfp16
  -mmultivalue
  -mmutable-globals
  -mnontrapping-fptoint
  -mrelaxed-simd
  -msign-ext
  -msimd128
)
if [[ -n "${CFLAGS:-}" ]]; then
  read -r -a CFLAGS_ARR <<< "$CFLAGS"
else
  CFLAGS_ARR=("${DEFAULT_CFLAGS[@]}")
fi

# Strip the random mktemp prefix from embedded __FILE__ strings so rebuilding
# produces byte-identical binaries.
PREFIX_MAP_FLAGS=(
  -ffile-prefix-map="$NCNN_SRC"=ncnn
  -ffile-prefix-map="$BUILD_DIR"=ncnn-build
)

EM_LDFLAGS=(
  -sENVIRONMENT=web
  -sMODULARIZE=1
  -sEXPORT_ES6=1
  -sALLOW_MEMORY_GROWTH=1
  -sINITIAL_MEMORY=256MB
  -sFORCE_FILESYSTEM=1
  -sEXPORTED_RUNTIME_METHODS=FS,callMain
)

COMPILE_FLAGS="${CFLAGS_ARR[*]} ${PREFIX_MAP_FLAGS[*]}"

# Only the ncnn library is built through CMake. benchncnn is linked separately
# below so we control the Emscripten link settings for the browser (the
# upstream benchmark target links nodefs.js).
#
# Threads/OpenMP are disabled to match wasm-perf's single-threaded run.
# NCNN_RUNTIME_CPU is OFF because Emscripten has no runtime-dispatched ISA
# variants; SIMD comes from NCNN_SSE2 which ncnn maps to -msimd128 under
# Emscripten.
echo "[ncnn] Configuring NCNN with Emscripten..."
emcmake cmake \
  -B "$BUILD_DIR" \
  -S "$NCNN_SRC" \
  -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
  -DCMAKE_C_FLAGS="$COMPILE_FLAGS" \
  -DCMAKE_CXX_FLAGS="$COMPILE_FLAGS" \
  -DNCNN_OPENMP=OFF \
  -DNCNN_SIMPLEOMP=OFF \
  -DNCNN_THREADS=OFF \
  -DNCNN_BENCHMARK=OFF \
  -DNCNN_RUNTIME_CPU=OFF \
  -DNCNN_SSE2=ON \
  -DNCNN_VULKAN=OFF \
  -DNCNN_BUILD_BENCHMARK=OFF \
  -DNCNN_BUILD_TOOLS=OFF \
  -DNCNN_BUILD_EXAMPLES=OFF \
  -DNCNN_BUILD_TESTS=OFF

echo "[ncnn] Building NCNN library with $EMCC_VERSION..."
cmake --build "$BUILD_DIR" --target ncnn --parallel

mkdir -p "$STAGE_DIR" "$STAGE_DATA_DIR"

echo "[ncnn] Linking benchncnn.mjs + benchncnn.wasm..."
"$CXX" "${CFLAGS_ARR[@]}" "${PREFIX_MAP_FLAGS[@]}" "${EM_LDFLAGS[@]}" \
  "$NCNN_SRC/benchmark/benchncnn.cpp" \
  -I "$NCNN_SRC/src" \
  -I "$BUILD_DIR/src" \
  "$BUILD_DIR/src/libncnn.a" \
  -o "$STAGE_DIR/benchncnn.mjs"

for f in "${PARAM_FILES[@]}"; do
  cp "$NCNN_SRC/benchmark/$f" "$STAGE_DATA_DIR/$f"
done

cat > "$STAGE_DIR/README.md" <<EOF
# NCNN benchncnn (Wasm)

Auto-generated by \`resources/experimental/build-wasm-workloads.sh\`. Do not edit manually.

The files in this directory are checked in so that Emscripten and CMake are not
required to build or deploy the benchmark. To refresh them, activate emsdk,
install CMake, and run:

\`\`\`bash
resources/experimental/build-wasm-workloads.sh ncnn
\`\`\`

- Source: [ncnn](https://github.com/Tencent/ncnn) [\`$NCNN_VERSION\`](https://github.com/Tencent/ncnn/releases/tag/$NCNN_VERSION) (full-source release, patched with \`ncnn.patch\`)
- Data: \`benchmark/*.param\` network topologies from the ncnn source release
- Compiler: \`$EMCC_VERSION\`
- CMake: \`$CMAKE_VERSION\`
- CFLAGS: \`${CFLAGS_ARR[*]}\`
- LDFLAGS: \`${EM_LDFLAGS[*]}\`
EOF

rm -rf "$OUT_DIR"
mv "$STAGE_DIR" "$OUT_DIR"

echo "[ncnn] Successfully built NCNN Wasm module and param files in $OUT_DIR"
