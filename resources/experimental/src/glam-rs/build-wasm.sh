set -euo pipefail
export LC_ALL=C

GLAM_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
OUT_DIR="$GLAM_DIR/build"

# Must match BENCH_MODULES in benchmark.mjs. This is the reduced subset of
# glam's criterion benches used by wasm-perf/benchmarks/glam_rs/glam_rs.py.
BENCHES=(
  affine2
  affine3
  mat2
  mat3
  quat
  vec2
  vec4
)

for cmd in cargo rustc rustup emcc git patch; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Error: $cmd not found. Please ensure Rust (cargo/rustc/rustup), Emscripten (emcc), git and patch are in PATH." >&2
    exit 1
  fi
done

CARGO_VERSION="$(cargo --version)"
RUSTC_VERSION="$(rustc --version)"
EMCC_VERSION="$(emcc --version | head -n 1)"

rustup target add wasm32-unknown-emscripten

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

GLAM_SRC="$WORK_DIR/glam-rs"
TARGET_DIR="${CARGO_TARGET_DIR:-$WORK_DIR/target}"
# Build into a staging directory and only replace the checked-in output once
# everything succeeded, so a failed build never leaves src/glam-rs/build/ empty.
STAGE_DIR="$WORK_DIR/out"

GLAM_VERSION="0.30.5"

# glam's workspace references the `codegen` git submodule, which is not part of
# the GitHub release tarballs, so clone (like wasm-perf) instead of downloading
# an archive.
echo "[glam-rs] Cloning glam-rs ($GLAM_VERSION)..."
git -c advice.detachedHead=false clone --quiet --depth=1 --shallow-submodules --recursive \
  --branch "$GLAM_VERSION" https://github.com/bitshifter/glam-rs.git "$GLAM_SRC"
GLAM_COMMIT="$(git -C "$GLAM_SRC" rev-parse HEAD)"
patch -i "$GLAM_DIR/glam-rs.patch" -p 1 --directory="$GLAM_SRC"

# wasm-perf builds glam_rs with opt-level=3 plus its common set of Wasm target
# features.
DEFAULT_RUSTFLAGS=(
  -C opt-level=3
  -C target-feature=+bulk-memory
  -C target-feature=+extended-const
  -C target-feature=+multivalue
  -C target-feature=+mutable-globals
  -C target-feature=+nontrapping-fptoint
  -C target-feature=+relaxed-simd
  -C target-feature=+sign-ext
  -C target-feature=+simd128
  -C link-arg=-sENVIRONMENT=web
  -C link-arg=-sMODULARIZE=1
  -C link-arg=-sEXPORT_ES6=1
  -C link-arg=-sALLOW_MEMORY_GROWTH=1
)

export CARGO_TARGET_WASM32_UNKNOWN_EMSCRIPTEN_RUSTFLAGS="${RUSTFLAGS:-${DEFAULT_RUSTFLAGS[*]}}"
export CARGO_TARGET_DIR="$TARGET_DIR"

BENCH_ARGS=()
for bench in "${BENCHES[@]}"; do
  BENCH_ARGS+=(--bench "$bench")
done

# Bench targets are built like libs, with a hash appended to the output file
# name, so start from a clean target directory to guarantee a single match per
# bench below.
cargo clean --manifest-path="$GLAM_SRC/Cargo.toml"

echo "[glam-rs] Compiling glam criterion benches to Wasm with $RUSTC_VERSION and $EMCC_VERSION..."
cargo build --target wasm32-unknown-emscripten --release \
  --manifest-path="$GLAM_SRC/Cargo.toml" \
  "${BENCH_ARGS[@]}"

mkdir -p "$STAGE_DIR"

DEPS_DIR="$TARGET_DIR/wasm32-unknown-emscripten/release/deps"
for bench in "${BENCHES[@]}"; do
  js_files=("$DEPS_DIR/$bench"-*.js)
  if [[ ${#js_files[@]} -ne 1 || ! -f "${js_files[0]}" ]]; then
    echo "Error: expected exactly one $bench-*.js in $DEPS_DIR, found: ${js_files[*]}" >&2
    exit 1
  fi
  hashed_name="$(basename "${js_files[0]}" .js)"
  # Drop the cargo hash from the file names and from the default .wasm path
  # referenced by the Emscripten JS glue.
  sed "s/$hashed_name\.wasm/$bench.wasm/g" "${js_files[0]}" > "$STAGE_DIR/$bench.mjs"
  cp "$DEPS_DIR/$hashed_name.wasm" "$STAGE_DIR/$bench.wasm"
done

cat > "$STAGE_DIR/README.md" <<EOF
# glam-rs criterion benches (Wasm)

Auto-generated by \`resources/experimental/build-wasm-workloads.sh\`. Do not edit manually.

The files in this directory are checked in so that Rust and Emscripten are not
required to build or deploy the benchmark. To refresh them, install Rust and
activate emsdk, then run:

\`\`\`bash
resources/experimental/build-wasm-workloads.sh glam-rs
\`\`\`

- Source: [glam-rs](https://github.com/bitshifter/glam-rs) [\`$GLAM_VERSION\`](https://github.com/bitshifter/glam-rs/tree/$GLAM_COMMIT) (patched with \`glam-rs.patch\`)
- Benches: \`${BENCHES[*]}\`
- Rust Compiler: \`$RUSTC_VERSION\` (\`$CARGO_VERSION\`)
- Emscripten: \`$EMCC_VERSION\`
- RUSTFLAGS: \`$CARGO_TARGET_WASM32_UNKNOWN_EMSCRIPTEN_RUSTFLAGS\`
EOF

rm -rf "$OUT_DIR"
mv "$STAGE_DIR" "$OUT_DIR"

echo "[glam-rs] Successfully built glam-rs Wasm modules in $OUT_DIR"
