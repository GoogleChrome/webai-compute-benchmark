set -euo pipefail

TRACT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
OUT_DIR="$TRACT_DIR/build"
OUT_DATA_DIR="$OUT_DIR/data"

DATA_FILES=(
  "elephants.jpg"
  "grace_hopper.jpg"
  "mobilenet_v3_small_100_224.tflite"
  "mobilenetv2-7-qdq.onnx"
  "mobilenetv2-7-qo.onnx"
  "mobilenetv2-7.onnx"
  "resnet-qdq.onnx"
  "resnet-qo.onnx"
  "resnet.onnx"
)

WASM_DATA_BASE_URL="https://gitlab.arm.com/runtimes/wasm-perf/-/raw/main/benchmarks/tract/data"

for cmd in cargo rustc rustup emcc curl tar patch; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Error: $cmd not found. Please ensure Rust (cargo/rustc/rustup) and Emscripten (emcc) are in PATH." >&2
    exit 1
  fi
done

CARGO_VERSION="$(cargo --version)"
RUSTC_VERSION="$(rustc --version)"
EMCC_VERSION="$(emcc --version | head -n 1)"

rustup target add wasm32-unknown-emscripten

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

TRACT_SRC="$WORK_DIR/tract"
TARGET_DIR="${CARGO_TARGET_DIR:-$WORK_DIR/target}"

TRACT_VERSION="0.22.0"

echo "[tract] Downloading Tract ($TRACT_VERSION)..."
mkdir -p "$TRACT_SRC"
curl -LSfs "https://github.com/sonos/tract/archive/refs/tags/$TRACT_VERSION.tar.gz" \
  | tar --strip-components=1 -xz -C "$TRACT_SRC"
patch -i "$TRACT_DIR/tract.patch" -p 1 --directory="$TRACT_SRC"

DEFAULT_RUSTFLAGS=(
  -C opt-level=2
  -C target-feature=+bulk-memory
  -C target-feature=+extended-const
  -C target-feature=+multivalue
  -C target-feature=+mutable-globals
  -C target-feature=+nontrapping-fptoint
  -C target-feature=+relaxed-simd
  -C target-feature=+sign-ext
  -C target-feature=+simd128
  -C link-arg=-sENVIRONMENT=web
  -C link-arg=-sMODULARIZE=1
  -C link-arg=-sEXPORT_ES6=1
  -C link-arg=-sINVOKE_RUN=0
  -C link-arg=-sALLOW_MEMORY_GROWTH=1
  -C link-arg=-sFORCE_FILESYSTEM=1
  -C link-arg=-sEXPORTED_RUNTIME_METHODS=FS,callMain
)

export CARGO_TARGET_WASM32_UNKNOWN_EMSCRIPTEN_RUSTFLAGS="${RUSTFLAGS:-${DEFAULT_RUSTFLAGS[*]}}"
export CARGO_TARGET_DIR="$TARGET_DIR"

echo "[tract] Compiling Tract example binaries to Wasm with $RUSTC_VERSION and $EMCC_VERSION..."
cargo build --target wasm32-unknown-emscripten --release \
  --manifest-path="$TRACT_SRC/Cargo.toml" \
  -p example-onnx-mobilenet-v2 --bin example-onnx-mobilenet-v2 \
  -p example-tflite-mobilenet-v3 --bin example-tflite-mobilenet-v3 \
  -p example-pytorch-resnet --bin example-pytorch-resnet

mkdir -p "$OUT_DIR" "$OUT_DATA_DIR"

RELEASE_DIR="$TARGET_DIR/wasm32-unknown-emscripten/release"
for bin in example-onnx-mobilenet-v2 example-pytorch-resnet example-tflite-mobilenet-v3; do
  wasm_name="${bin//-/_}.wasm"
  cp "$RELEASE_DIR/$bin.js" "$OUT_DIR/$bin.mjs"
  cp "$RELEASE_DIR/$wasm_name" "$OUT_DIR/$wasm_name"
done

for f in "${DATA_FILES[@]}"; do
  if [[ ! -f "$OUT_DATA_DIR/$f" ]]; then
    echo "[tract] Downloading Tract data file $f..."
    curl -LSfs "$WASM_DATA_BASE_URL/$f" -o "$OUT_DATA_DIR/$f.tmp"
    mv "$OUT_DATA_DIR/$f.tmp" "$OUT_DATA_DIR/$f"
  fi
done

cp "$TRACT_SRC/LICENSE-APACHE" "$OUT_DIR/LICENSE"

cat > "$OUT_DIR/README.md" <<EOF
# Tract Example Binaries & Models (Wasm)

Auto-generated by \`resources/experimental/build-wasm-workloads.sh\`. Do not edit manually.

The files in this directory are checked in so that Rust and Emscripten are not
required to build or deploy the benchmark. To refresh them, install Rust and
activate emsdk, then run:

\`\`\`bash
resources/experimental/build-wasm-workloads.sh tract
\`\`\`

- Source: [tract](https://github.com/sonos/tract) [\`$TRACT_VERSION\`](https://github.com/sonos/tract/tree/$TRACT_VERSION) (patched with \`tract.patch\`)
- Data: [wasm-perf/benchmarks/tract/data]($WASM_DATA_BASE_URL)
- Rust Compiler: \`$RUSTC_VERSION\` (\`$CARGO_VERSION\`)
- Emscripten: \`$EMCC_VERSION\`
- RUSTFLAGS: \`$CARGO_TARGET_WASM32_UNKNOWN_EMSCRIPTEN_RUSTFLAGS\`
EOF

echo "[tract] Successfully built Tract Wasm modules and data in $OUT_DIR"
