set -euo pipefail

MESHOPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
OUT_DIR="$MESHOPT_DIR/build"

CXX="${CXX:-em++}"
if ! command -v "$CXX" >/dev/null 2>&1; then
  echo "Error: $CXX not found. Please activate emsdk or set CXX." >&2
  exit 1
fi
EMCC_VERSION="$("$CXX" --version | head -n 1)"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

MESHOPT_SRC="$WORK_DIR/meshoptimizer"
MESHOPT_VERSION="v0.25"

DEFAULT_CFLAGS=(
  -O2
  -fno-exceptions
  -mbulk-memory
  -mextended-const
  -mmultivalue
  -mmutable-globals
  -mnontrapping-fptoint
  -mrelaxed-simd
  -msign-ext
  -msimd128
)
if [[ -n "${CFLAGS:-}" ]]; then
  read -r -a CFLAGS_ARR <<< "$CFLAGS"
else
  CFLAGS_ARR=("${DEFAULT_CFLAGS[@]}")
fi

# codecbench allocates several hundred MB of linear memory per run (~64 MB of
# source vertices plus decode/encode buffers, index buffers, and 32/64 MB filter
# buffers). Instantiating a fresh module for every sub-iteration would keep
# each instance's WebAssembly.Memory alive until GC, risking OOM and GC pauses
# on low-memory devices. Instead, benchmark.mjs instantiates the module once
# and re-runs main() for each sub-iteration:
#   -sINVOKE_RUN=0: don't run main() automatically on instantiation.
#   -sEXPORTED_RUNTIME_METHODS=callMain: expose callMain() so benchmark.mjs
#     can invoke main() explicitly, reusing the same instance and heap.
EM_LDFLAGS=(
  -sENVIRONMENT=web
  -sMODULARIZE=1
  -sEXPORT_ES6=1
  -sINVOKE_RUN=0
  -sEXPORTED_RUNTIME_METHODS=callMain
  -sALLOW_MEMORY_GROWTH=1
)

DEFINES=(
  -DNDEBUG
  -ffile-prefix-map="$MESHOPT_SRC"=meshoptimizer
)

echo "[meshoptimizer] Downloading Meshoptimizer ($MESHOPT_VERSION)..."
mkdir -p "$MESHOPT_SRC"
curl -LSsf "https://github.com/zeux/meshoptimizer/archive/refs/tags/$MESHOPT_VERSION.tar.gz" \
  | tar --strip-components=1 -xz -C "$MESHOPT_SRC"

rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR"

echo "[meshoptimizer] Compiling codecbench.mjs + codecbench.wasm with $EMCC_VERSION..."
"$CXX" "${CFLAGS_ARR[@]}" "${DEFINES[@]}" "${EM_LDFLAGS[@]}" \
  "$MESHOPT_SRC"/src/*.cpp \
  "$MESHOPT_SRC"/tools/codecbench.cpp \
  -o "$OUT_DIR/codecbench.mjs"

cp "$MESHOPT_SRC/LICENSE.md" "$OUT_DIR/LICENSE"

cat > "$OUT_DIR/README.md" <<EOF
# Meshoptimizer codecbench (Wasm)

Auto-generated by \`resources/experimental/build-wasm-workloads.sh\`. Do not edit manually.

The files in this directory are checked in so that Emscripten is not required
to build or deploy the benchmark. To refresh them, activate emsdk and run:

\`\`\`bash
resources/experimental/build-wasm-workloads.sh meshoptimizer
\`\`\`

- Source: [meshoptimizer](https://github.com/zeux/meshoptimizer) [\`$MESHOPT_VERSION\`](https://github.com/zeux/meshoptimizer/tree/$MESHOPT_VERSION)
- Compiler: \`$EMCC_VERSION\`
- CFLAGS: \`${CFLAGS_ARR[*]}\`
- LDFLAGS: \`${EM_LDFLAGS[*]}\`
EOF

echo "[meshoptimizer] Successfully built Meshoptimizer Wasm module in $OUT_DIR"
